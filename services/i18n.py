def get_request_language(request: Request | None) -> str:
    """
    Detect the preferred UI language for a request.
    Priority:
    1. Query param: `?lang=es`
    2. Cookie: `athenea_lang`
    3. Accept-Language header
    4. Default: 'en'
    """
    if not request:
        return DEFAULT_LANGUAGE

    # 1. Query parameter
    lang_param = request.query_params.get("lang")
    if lang_param and lang_param.lower() in SUPPORTED_CODES:
        return lang_param.lower()

    # 2. Cookie
    cookie_lang = request.cookies.get(COOKIE_NAME)
    if cookie_lang and cookie_lang.lower() in SUPPORTED_CODES:
        return cookie_lang.lower()

    # 3. Accept-Language header
    accept = request.headers.get("accept-language", "")
    if accept:
        for part in accept.split(","):
            code = part.split(";")[0].strip().lower()
            # check 2-letter prefix, e.g. 'es-ES' -> 'es'
            primary = code.split("-")[0]
            if primary in SUPPORTED_CODES:
                return primary

    return DEFAULT_LANGUAGE


def get_language_meta(code: str) -> dict[str, str]:
    """Retrieve metadata (flag, name, native) for a language code."""
    for lang in SUPPORTED_LANGUAGES:
        if lang["code"] == code:
            return lang
    return SUPPORTED_LANGUAGES[0]


